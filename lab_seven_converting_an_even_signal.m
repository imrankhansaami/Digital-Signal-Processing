clc;
clear all;
close all;
n = input('Enter the range of n ');
x = input('Enter the signal values ');
x_rev = fliplr(x);
x_even = (x+x_rev)/2;
subplot(3,1,1);
stem(n,x, 'filled');
title('Original signal x(n):');
xlabel('n');
ylabel('Amplititude');
grid on;
subplot(3,1,2);
stem(n,x_rev,'filled');
title('Reversed Signal x(-n)');
xlabel('n');
ylabel('Amplititude');
grid on;
subplot(3,1,3);
stem(n,x_even, 'filled');
title('Even signal x_e(n)');
xlabel('n');
ylabel('amplititude');
grid on;